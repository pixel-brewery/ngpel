/**
 * Accessible labels used by image preview controls.
 *
 * @public
 */
export interface IImagePreviewLabels {
    /**
     * Close action label.
     *
     * @public
     * @readonly
     */
    readonly close: string;

    /**
     * Next image action label.
     *
     * @public
     * @readonly
     */
    readonly next: string;

    /**
     * Previous image action label.
     *
     * @public
     * @readonly
     */
    readonly previous: string;

    /**
     * Rotate counter-clockwise action label.
     *
     * @public
     * @readonly
     */
    readonly rotateLeft: string;

    /**
     * Rotate clockwise action label.
     *
     * @public
     * @readonly
     */
    readonly rotateRight: string;

    /**
     * Viewer dialog label.
     *
     * @public
     * @readonly
     */
    readonly viewer: string;

    /**
     * Zoom in action label.
     *
     * @public
     * @readonly
     */
    readonly zoomIn: string;

    /**
     * Zoom out action label.
     *
     * @public
     * @readonly
     */
    readonly zoomOut: string;
}
