/**
 * RFC 9457 Problem Detail for HTTP APIs.
 *
 * Represents a structured error response following the Problem Details standard.
 * Backend services (for example Archipel's `ProblemDetailExceptionFilter`) return this
 * format with `Content-Type: application/problem+json`.
 *
 * @public
 */
export interface IProblemDetail {
    // #region Properties

    /**
     * A URI reference that identifies the problem type.
     */
    readonly type?: string;

    /**
     * A short, human-readable summary of the problem type.
     */
    readonly title: string;

    /**
     * The HTTP status code generated by the origin server.
     */
    readonly status: number;

    /**
     * A human-readable explanation specific to this occurrence of the problem.
     */
    readonly detail?: string;

    /**
     * A URI reference that identifies the specific occurrence of the problem.
     */
    readonly instance?: string;

    /**
     * A machine-readable error code identifying the specific domain error.
     */
    readonly code?: string;

    /**
     * Extension members for additional context.
     */
    readonly [key: string]: unknown;

    // #endregion
}
